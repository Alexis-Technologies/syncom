/**
 * The feature matrices of the docs, rendered from data so a table and its data
 * cannot drift. Each page below has a JSON file with the libraries in columns
 * and the features in rows grouped by area; the table goes into the region
 * between `<!-- comparison:start -->` and `<!-- comparison:end -->` of the
 * page. A cell is `{ mark, text, note? }`: the mark is one of ✅ ⚠️ ❌ 🔜 —,
 * the text a few words (backticks become code), and a note becomes a numbered
 * footnote under the table.
 *
 * The first library of the data is syncom: custom.css tints the second
 * column of the table in the brand colour and pins it beside the features.
 * Every cell of the alternatives was decided by reading the source of the
 * published package and its official docs (see each page for the method); a
 * cell's `source` (and, for a footnote left out of the table, its `detail`)
 * stays in the data for whoever checks it again. Edit the data, not the table.
 *
 * Run: pnpm docs:comparison
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const PAGES = [
  // Every alternative at once: /guide/comparison.
  { data: path.join(ROOT, 'docs', 'comparison.json'), target: path.join(ROOT, 'docs', 'guide', 'comparison.md') },
  // syncom and RxDB, feature by feature: /guide/vs-rxdb.
  { data: path.join(ROOT, 'docs', 'comparison-rxdb.json'), target: path.join(ROOT, 'docs', 'guide', 'vs-rxdb.md') },
];
const START = '<!-- comparison:start -->';
const END = '<!-- comparison:end -->';

const escape = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// `code` spans and [links](url), the only markup a cell or a note uses.
const inline = (text) =>
  escape(text)
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>');

// One table of the groups given; `noteOf` numbers the footnotes across all of a page's tables.
const renderTable = (columns, groups, noteOf) => {
  const lines = ['<table>', '<thead>', '<tr>', '<th>Feature</th>'];
  for (const library of columns) {
    const name = `<a href="${library.url}">${escape(library.name)}</a>`;
    lines.push(`<th>${name}<br><sub>${escape(library.direction)}</sub></th>`);
  }
  lines.push('</tr>', '</thead>', '<tbody>');
  for (const group of groups) {
    lines.push(
      `<tr class="sc-matrix-group"><td colspan="${columns.length + 1}"><strong>${escape(group.title)}</strong></td></tr>`,
    );
    for (const row of group.rows) {
      const cells = [`<td>${inline(row.title)}</td>`];
      for (const library of columns) {
        const cell = library.cells[row.id];
        if (!cell) throw new Error(`${library.id}: no cell for "${row.id}"`);
        const parts = [];
        if (cell.mark) parts.push(cell.mark);
        if (cell.text) parts.push(inline(cell.text));
        const note = cell.note ? noteOf(cell.note) : '';
        cells.push(`<td>${parts.join(' ')}${note}</td>`);
      }
      lines.push(`<tr>${cells.join('')}</tr>`);
    }
  }
  lines.push('</tbody>', '</table>');
  return lines.join('\n');
};

// Consecutive groups that share a `section` make one table under a `###`
// heading of that name; without sections the page has a single table.
const sectionsOf = (groups) => {
  const sections = [];
  for (const group of groups) {
    const last = sections.at(-1);
    if (last && last.title === (group.section ?? null)) last.groups.push(group);
    else sections.push({ title: group.section ?? null, groups: [group] });
  }
  return sections;
};

const render = (data) => {
  const notes = [];
  const noteOf = (text) => {
    let index = notes.indexOf(text);
    if (index === -1) index = notes.push(text) - 1;
    return `<sup>${index + 1}</sup>`;
  };
  const className = data.className || 'sc-matrix';
  const tables = sectionsOf(data.groups).map(({ title, groups }) => {
    const table = `<div class="${className}">\n\n${renderTable(data.libraries, groups, noteOf)}\n\n</div>`;
    return title ? `### ${title}\n\n${table}` : table;
  });
  const list = notes.map((text, i) => `${i + 1}. ${inline(text)}`).join('\n');
  return { tables, notes: list, sectioned: tables.length > 1 };
};

const update = ({ data: source, target }) => {
  const data = JSON.parse(fs.readFileSync(source, 'utf8'));
  const { tables, notes, sectioned } = render(data);
  // A single table reads with its legend under it; sections need the legend first.
  const content = sectioned
    ? [data.legend, ...tables, notes && `### Notes\n\n${notes}`].filter(Boolean)
    : [...tables, data.legend, notes].filter(Boolean);
  const generated =
    `<!-- generated by \`pnpm docs:comparison\` from ${path.relative(ROOT, source)}` +
    ' — edit the data, not this block -->';
  const text = fs.readFileSync(target, 'utf8');
  const from = text.indexOf(START);
  const to = text.indexOf(END);
  if (from === -1 || to === -1) {
    console.warn(`${path.relative(ROOT, target)}: no comparison markers, skipped`);
    return;
  }
  const next = `${text.slice(0, from + START.length)}\n${generated}\n\n${content.join('\n\n')}\n\n${text.slice(to)}`;
  fs.writeFileSync(target, next);
  console.log(`updated ${path.relative(ROOT, target)}`);
};

for (const page of PAGES) update(page);
