/**
 * The feature matrix of docs/guide/comparison.md: one table, @alexify/mailer
 * and the alternatives in columns, the features in rows grouped by area,
 * rendered from docs/comparison.json into the region between
 * `<!-- comparison:start -->` and `<!-- comparison:end -->`, so the table and
 * the data cannot drift (CI regenerates it and fails on a diff). A cell is
 * `{ mark, text, note? }`: the mark is one of ✅ ⚠️ ❌ 🔜 —, the text a few
 * words (backticks become code), and a note becomes a numbered footnote under
 * the table.
 *
 * The first library of the data is syncom: custom.css tints the second
 * column of the table in the brand colour and pins it beside the features.
 * Every cell of the alternatives was decided by reading the source of the
 * published package and its official docs (see the page for the method); a
 * cell's `source` (and, for a footnote left out of the table, its `detail`)
 * stays in the data for whoever checks it again. Edit the data, not the table.
 *
 * Run: pnpm docs:comparison
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'docs', 'comparison.json');
const TARGETS = [path.join(ROOT, 'docs', 'guide', 'comparison.md')];
const START = '<!-- comparison:start -->';
const END = '<!-- comparison:end -->';
const GENERATED =
  '<!-- generated by `pnpm docs:comparison` from docs/comparison.json — edit the data, not this block -->';

const escape = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// `code` spans and [links](url), the only markup a cell or a note uses.
const inline = (text) =>
  escape(text)
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>');

const render = (data) => {
  const notes = [];
  const noteOf = (text) => {
    let index = notes.indexOf(text);
    if (index === -1) index = notes.push(text) - 1;
    return `<sup>${index + 1}</sup>`;
  };
  const columns = data.libraries;
  const lines = ['<table>', '<thead>', '<tr>', '<th>Feature</th>'];
  for (const library of columns) {
    const name = `<a href="${library.url}">${escape(library.name)}</a>`;
    lines.push(`<th>${name}<br><sub>${escape(library.direction)}</sub></th>`);
  }
  lines.push('</tr>', '</thead>', '<tbody>');
  for (const group of data.groups) {
    lines.push(
      `<tr class="sc-matrix-group"><td colspan="${columns.length + 1}"><strong>${escape(group.title)}</strong></td></tr>`,
    );
    for (const row of group.rows) {
      const cells = [`<td>${inline(row.title)}</td>`];
      for (const library of columns) {
        const cell = library.cells[row.id];
        if (!cell) throw new Error(`${library.id}: no cell for "${row.id}"`);
        const parts = [];
        if (cell.mark) parts.push(cell.mark);
        if (cell.text) parts.push(inline(cell.text));
        const note = cell.note ? noteOf(cell.note) : '';
        cells.push(`<td>${parts.join(' ')}${note}</td>`);
      }
      lines.push(`<tr>${cells.join('')}</tr>`);
    }
  }
  lines.push('</tbody>', '</table>');
  const list = notes.map((text, i) => `${i + 1}. ${inline(text)}`).join('\n');
  return { table: lines.join('\n'), notes: list };
};

const main = () => {
  const data = JSON.parse(fs.readFileSync(DATA, 'utf8'));
  const { table, notes } = render(data);
  const legend = data.legend;
  const content = [`<div class="sc-matrix">\n\n${table}\n\n</div>`, legend, notes].join('\n\n');
  for (const file of TARGETS) {
    const text = fs.readFileSync(file, 'utf8');
    const from = text.indexOf(START);
    const to = text.indexOf(END);
    if (from === -1 || to === -1) {
      console.warn(`${path.relative(ROOT, file)}: no comparison markers, skipped`);
      continue;
    }
    const next = `${text.slice(0, from + START.length)}\n${GENERATED}\n\n${content}\n\n${text.slice(to)}`;
    fs.writeFileSync(file, next);
    console.log(`updated ${path.relative(ROOT, file)}`);
  }
};

main();
