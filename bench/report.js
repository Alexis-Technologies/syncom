'use strict';

/**
 * Turns the benchmark results into what the docs and the README show:
 * - SVG charts in docs/public/benchmarks/ (served by the docs site and
 *   embedded by the README, where no script can render the interactive
 *   charts of the docs);
 * - the tables between `<!-- bench:<name>:start -->` and `:end -->` markers
 *   in README.md and docs/guide/benchmarks.md (the docs pages render the same
 *   models interactively above them).
 * Both come from bench/report/model.mjs, so a chart and its table cannot
 * disagree. Text outside the markers is never touched.
 *
 * The inputs: bench/results/compare.json (pnpm bench:compare),
 * bench/results/size.json (pnpm bench:size) and bench/results/engine.json
 * (pnpm bench --save).
 *
 * Run: pnpm bench:report
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const RESULTS = path.join(__dirname, 'results');
const SVG_DIR = path.join(ROOT, 'docs', 'public', 'benchmarks');
const IMAGE_BASE = 'https://syncomjs.vercel.app/benchmarks';
const TARGETS = {
  readme: path.join(ROOT, 'README.md'),
  docs: path.join(ROOT, 'docs', 'guide', 'benchmarks.md'),
};
// The scenarios the README shows open; the rest sit in a <details>.
const HEADLINES = ['sync-memory', 'insert-disk'];
const GENERATED = '<!-- generated by `pnpm bench:report` from bench/results — edit the results, not this block -->';

const readJson = (file) => {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch {
    console.warn(`${path.relative(ROOT, file)} not found, skipping its charts and tables`);
    return null;
  }
};

const kb = (bytes) => `${(bytes / 1024).toFixed(1)} KB`;
const ms = (value) => `${value.toFixed(1)} ms`;

const table = (header, align, rows) =>
  [`| ${header.join(' | ')} |`, `| ${align.join(' | ')} |`, ...rows.map((row) => `| ${row.join(' | ')} |`)].join('\n');

// The name on the first line, what was timed and the version underneath (the
// HTML renders on GitHub, npm and VitePress).
const libraryCell = (library, line) => {
  const own = library.package === '@alexify/syncom';
  const name = own ? `**${library.name}**` : library.name;
  const variant = line ? library.lines?.[line] : null;
  return `${name}<br><sub>${variant ? `${variant} · ` : ''}v${library.version}</sub>`;
};

const image = (file, alt) => `<img src="${IMAGE_BASE}/${file}" alt="${alt.replace(/"/g, '&quot;')}" width="760" />`;

const details = (summary, items) => [`<details>\n<summary>${summary}</summary>`, ...items, '</details>'].join('\n\n');

const main = async () => {
  const model = await import('./report/model.mjs');
  const { renderSvg } = await import('./report/svg.mjs');
  const compare = readJson(path.join(RESULTS, 'compare.json'));
  const size = readJson(path.join(RESULTS, 'size.json'));
  const engine = readJson(path.join(RESULTS, 'engine.json'));

  fs.mkdirSync(SVG_DIR, { recursive: true });
  const writeSvg = (file, chart, caption) => {
    fs.writeFileSync(path.join(SVG_DIR, file), renderSvg(chart, { caption }));
    console.log(`wrote docs/public/benchmarks/${file}`);
  };

  // name → { readme, docs } markdown
  const regions = {};

  if (compare) {
    const caption = model.compareCaption(compare);
    const headlines = [];
    const more = [];
    for (const scenario of compare.scenarios) {
      const chart = model.compareModel(compare, scenario.id, 'log');
      writeSvg(`compare-${scenario.id}.svg`, chart, caption);
      const img = image(`compare-${scenario.id}.svg`, `${chart.title}: ${chart.subtitle}`);
      if (HEADLINES.includes(scenario.id)) headlines[HEADLINES.indexOf(scenario.id)] = img;
      else more.push(img);
    }
    // One table per line: the kinds in columns, a library per row.
    const tables = [];
    for (const line of ['memory', 'disk']) {
      const scenarios = compare.scenarios.filter((scenario) => scenario.line === line);
      if (!scenarios.length) continue;
      const libraries = compare.libraries.filter((library) => library.lines?.[line]);
      tables.push(
        `**${scenarios[0].lineTitle}**`,
        table(
          ['Library', ...scenarios.map((scenario) => `${scenario.kindTitle}<br><sub>${scenario.unit}</sub>`)],
          ['---', ...scenarios.map(() => '---:')],
          libraries.map((library) => [
            libraryCell(library, line),
            ...scenarios.map((scenario) => {
              const result = scenario.results[library.id];
              if (result) return model.approx(result.median);
              return scenario.failed?.[library.id] ? 'failed' : '—';
            }),
          ]),
        ),
      );
    }
    const note =
      `_${caption}. Medians, rounded to three significant figures; — where the library has no ` +
      'such operation, no such storage, or no in-process sync, failed where it did not finish twice (the chart ' +
      'above says why)._';
    regions.compare = {
      readme: [...headlines, details(`${more.length} more scenarios`, more), ...tables, note].join('\n\n'),
      docs: [...tables, note].join('\n\n'),
    };

    if (compare.coldStart && Object.keys(compare.coldStart).length) {
      const cold = model.coldStartModel(compare);
      writeSvg('coldstart.svg', cold, model.machineCaption(compare.machine));
      const coldTable = table(
        ['Library', 'Load and open', 'First read', 'Total'],
        ['---', '---:', '---:', '---:'],
        model.allRows(cold).map((row) => {
          const phases = compare.coldStart[row.id];
          const library = compare.libraries.find((candidate) => candidate.id === row.id);
          return [libraryCell(library, 'disk'), ms(phases.open), ms(phases.firstRead), ms(phases.total)];
        }),
      );
      regions.coldstart = {
        readme: image('coldstart.svg', `${cold.title}: ${cold.subtitle}`),
        docs: coldTable,
      };
    }
  }

  if (size) {
    const chart = model.sizeModel(size);
    writeSvg('size.svg', chart, `esbuild ${size.esbuild} · ${size.generatedAt.slice(0, 10)}`);
    const sizeTable = table(
      ['Library', 'What is bundled', 'min', 'min+gzip', ''],
      ['---', '---', '---:', '---:', '---'],
      model.allRows(chart).map((row) => {
        const library = size.libraries.find((candidate) => candidate.id === row.id);
        const own = library.id === 'syncom';
        const name = own ? `**${library.name}**` : library.name;
        const wasm = library.wasm ? `, WebAssembly ${kb(library.wasm)}` : '';
        return [
          `${name}<br><sub>${library.packages.join(', ')}</sub>`,
          library.entry,
          `${kb(library.min)}${wasm ? `<br><sub>${wasm.slice(2)}</sub>` : ''}`,
          kb(library.gzip),
          library.note ?? '',
        ];
      }),
    );
    regions.size = {
      readme: [image('size.svg', `${chart.title}: ${chart.subtitle}`), sizeTable].join('\n\n'),
      docs: sizeTable,
    };
  }

  if (engine) {
    const caption = model.engineCaption(engine);
    const tables = [];
    for (const subject of model.engineSubjects(engine)) {
      const chart = model.engineModel(engine, subject.id);
      writeSvg(`engine-${subject.id}.svg`, chart, caption);
      tables.push(
        details(`${subject.title} — ${chart.groups[0].rows.length} rows`, [
          table(
            ['Benchmark', 'ops/s', 'per operation'],
            ['---', '---:', '---:'],
            chart.groups[0].rows.map((row) => [
              row.sublabel ? `${row.label} — ${row.sublabel}` : row.label,
              model.grouped(row.value),
              model.perCall(row.value),
            ]),
          ),
        ]),
      );
    }
    const storage = model.engineModel(engine, 'storage');
    regions.engine = {
      readme: image('engine-storage.svg', `${storage.title}: ${storage.subtitle}`),
      docs: [...tables, `_${caption}._`].join('\n\n'),
    };
  }

  for (const [target, file] of Object.entries(TARGETS)) {
    let text = fs.readFileSync(file, 'utf8');
    let touched = false;
    for (const [name, content] of Object.entries(regions)) {
      const start = `<!-- bench:${name}:start -->`;
      const end = `<!-- bench:${name}:end -->`;
      const from = text.indexOf(start);
      const to = text.indexOf(end);
      if (from === -1 || to === -1 || content[target] === undefined) continue;
      text = `${text.slice(0, from + start.length)}\n${GENERATED}\n\n${content[target]}\n\n${text.slice(to)}`;
      touched = true;
    }
    if (!touched) continue;
    fs.writeFileSync(file, text);
    console.log(`updated ${path.relative(ROOT, file)}`);
  }
};

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
